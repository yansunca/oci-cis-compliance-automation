-- Native CIS evidence artifact downloads.
-- Original report files remain audit evidence; this cache gives APEX/ORDS a
-- clickable download path without exposing private Object Storage locators.

whenever sqlerror exit sql.sqlcode rollback

BEGIN
    EXECUTE IMMEDIATE q'[
CREATE TABLE cis_evidence_artifact_cache (
    artifact_id NUMBER GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    run_id VARCHAR2(128) NOT NULL,
    source_path VARCHAR2(1024) NOT NULL,
    artifact_file_name VARCHAR2(512) NOT NULL,
    mime_type VARCHAR2(255) NOT NULL,
    checksum VARCHAR2(128) NOT NULL,
    size_bytes NUMBER NOT NULL,
    content_blob BLOB NOT NULL,
    status VARCHAR2(30) DEFAULT 'ACTIVE' NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT pk_cis_evidence_artifact_cache PRIMARY KEY (artifact_id),
    CONSTRAINT fk_cis_evidence_artifact_run FOREIGN KEY (run_id)
        REFERENCES scan_run (run_id),
    CONSTRAINT uq_cis_evidence_artifact_source UNIQUE (run_id, source_path),
    CONSTRAINT ck_cis_evidence_artifact_status CHECK (status IN ('ACTIVE', 'RETIRED'))
)
]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
/

BEGIN
    EXECUTE IMMEDIATE q'[
CREATE INDEX ix_cis_evidence_artifact_run
    ON cis_evidence_artifact_cache (run_id)
]';
EXCEPTION
    WHEN OTHERS THEN
        IF SQLCODE != -955 THEN
            RAISE;
        END IF;
END;
